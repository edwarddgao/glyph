    // MARK: frequently used

    private static let recentsKey = "swipe.emoji.recents"

    /// Top 30 by use count, column-major like the native grid; the native
    /// default set until the user has used any.
    static func frequent() -> [String] {
        let counts = UserDefaults.standard.dictionary(forKey: recentsKey) as? [String: Int] ?? [:]
        if counts.isEmpty { return defaultFrequent }
        let used = counts.sorted { $0.value > $1.value }.map { $0.key }
        var out = Array(used.prefix(30))
        for e in defaultFrequent where out.count < 30 && !out.contains(e) { out.append(e) }
        return out
    }

    static func noteUse(_ emoji: String) {
        var counts = UserDefaults.standard.dictionary(forKey: recentsKey) as? [String: Int] ?? [:]
        counts[emoji, default: 0] += 1
        if counts.count > 200 {
            for (k, _) in counts.sorted(by: { $0.value < $1.value }).prefix(counts.count - 200) { counts.removeValue(forKey: k) }
        }
        UserDefaults.standard.set(counts, forKey: recentsKey)
    }
